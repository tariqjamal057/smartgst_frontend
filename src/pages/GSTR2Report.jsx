import { useState, useEffect } from "react";
import { useOutletContext } from "react-router-dom";
import * as XLSX from "xlsx";
import { saveAs } from "file-saver";
import "../styles/GSTR1Report.css";
import * as services from "../api/services";

const GSTR2Report = () => {
  const [mode, setMode] = useState("month");
  const [month, setMonth] = useState("");
  const [quarter, setQuarter] = useState("");
  const [fileType, setFileType] = useState("software_excel");
  const { collapsed } = useOutletContext();
  const [purchaseData, setPurchaseData] = useState([]);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const fetchData = async () => {
    setLoading(true);
    setError("");
    try {
      let from_date = "";
      let to_date = "";
      if (mode === "month" && month) {
        const [y, m] = month.split("-");
        from_date = `${y}-${m}-01`;
        const lastDay = new Date(y, m, 0).getDate();
        to_date = `${y}-${m}-${String(lastDay).padStart(2, "0")}`;
      } else if (mode === "quarter" && quarter) {
        const qMap = { Q1: ["04", "06"], Q2: ["07", "09"], Q3: ["10", "12"], Q4: ["01", "03"] };
        const [startM, endM] = qMap[quarter] || [];
        const fy = new Date().getFullYear();
        from_date = `${fy}-${startM}-01`;
        const lastDay = new Date(fy, parseInt(endM), 0).getDate();
        to_date = `${fy}-${endM}-${String(lastDay).padStart(2, "0")}`;
      }
      const res = await services.getGSTR2({ from_date, to_date });
      const payload = res.data || res;
      setPurchaseData(Array.isArray(payload) ? payload : payload.results || []);
    } catch (err) {
      setError("Failed to fetch GSTR-2 data.");
      setPurchaseData([]);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchData();
  }, [month, quarter, mode]);

  const setCellValue = (workbook, sheetName, cell, value) => {
    const sheet = workbook.Sheets[sheetName];
    if (!sheet) return;
    if (!sheet[cell]) {
      sheet[cell] = { t: typeof value === "number" ? "n" : "s", v: value };
    } else {
      sheet[cell].v = value;
    }
  };

  const downloadSoftwareExcel = () => {
    const workbook = XLSX.utils.book_new();
    const commonHeaders = [["GSTIN", "Supplier Name", "Invoice No", "Invoice Date", "Invoice Value", "Place Of Supply", "Reverse Charge", "Invoice Type", "GST Rate", "Taxable Value", "CESS"]];
    const commonRows = purchaseData.map((item) => [item.gstin, item.supplier, item.invoiceNo, item.invoiceDate, item.invoiceValue, item.placeOfSupply, item.reverseCharge, item.invoiceType, item.rate, item.taxableValue, item.cess]);

    const createSheet = (sheetName, data) => {
      const worksheet = XLSX.utils.aoa_to_sheet(data);
      worksheet["!cols"] = [{ wch: 20 }, { wch: 28 }, { wch: 18 }, { wch: 16 }, { wch: 18 }, { wch: 22 }, { wch: 18 }, { wch: 18 }, { wch: 12 }, { wch: 18 }, { wch: 12 }];
      XLSX.utils.book_append_sheet(workbook, worksheet, sheetName);
    };

    createSheet("General", [["Company Name", "GSTIN", "Financial Year"], ["Tax Mate enterprices", "09ABCDE1234F1Z5", "2024-25"]]);
    createSheet("B2B", [...commonHeaders, ...commonRows]);
    createSheet("Export", [...commonHeaders, ...commonRows]);
    createSheet("Reverse charge", [...commonHeaders, ...commonRows]);
    createSheet("Import Goods", [...commonHeaders, ...commonRows]);
    createSheet("Cr.Dr", [...commonHeaders, ...commonRows]);
    createSheet("Cr.Dr Unregistered", [...commonHeaders, ...commonRows]);
    createSheet("Nil Rated", [...commonHeaders, ...commonRows]);
    createSheet("ISD", [...commonHeaders, ...commonRows]);
    createSheet("TDS and TCS", [...commonHeaders, ...commonRows]);
    createSheet("Advance Paid", [...commonHeaders, ...commonRows]);
    createSheet("Advance Adjusted", [...commonHeaders, ...commonRows]);
    createSheet("ITC Reversal", [...commonHeaders, ...commonRows]);
    createSheet("HSN Summary", [["HSN Code", "Description", "Taxable Value", "GST Rate"], ...purchaseData.map((item) => ["5208", "Cotton Fabric", item.taxableValue, item.rate])]);
    createSheet("Master", [["System"], ["Generated By ERP"]]);
    createSheet("Dropdowns", [["Dropdown Values"], ["Regular"], ["SEZ"], ["Composition"]]);

    const excelBuffer = XLSX.write(workbook, { type: "array", bookType: "xlsx" });
    saveAs(new Blob([excelBuffer], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" }), "Software_GSTR2_Report.xlsx");
  };

  const downloadGovtExcel = async () => {
    try {
      const response = await fetch("/templates/GSTR2_Excel_Workbook_Template_V2.2.xlsx");
      if (!response.ok) throw new Error("Govt template not found.");
      const arrayBuffer = await response.arrayBuffer();
      const workbook = XLSX.read(arrayBuffer, { type: "array", cellStyles: true, cellFormula: true, cellDates: true });

      setCellValue(workbook, "General", "B4", "LAVI INDIA INDUSTRIES");
      setCellValue(workbook, "General", "B5", "09ABCDE1234F1Z5");
      setCellValue(workbook, "General", "B6", "2024-25");

      purchaseData.forEach((item, index) => {
        const row = index + 8;
        setCellValue(workbook, "B2B", `A${row}`, item.gstin);
        setCellValue(workbook, "B2B", `B${row}`, item.supplier);
        setCellValue(workbook, "B2B", `C${row}`, item.invoiceNo);
        setCellValue(workbook, "B2B", `D${row}`, item.invoiceDate);
        setCellValue(workbook, "B2B", `E${row}`, item.invoiceValue);
        setCellValue(workbook, "B2B", `F${row}`, item.taxableValue);
        setCellValue(workbook, "B2B", `G${row}`, item.rate);
        setCellValue(workbook, "Export", `A${row}`, item.invoiceNo);
        setCellValue(workbook, "Export", `B${row}`, item.invoiceDate);
        setCellValue(workbook, "Export", `C${row}`, item.invoiceValue);
        setCellValue(workbook, "Reverse charge", `A${row}`, item.gstin);
        setCellValue(workbook, "Reverse charge", `B${row}`, item.supplier);
        setCellValue(workbook, "Import Goods", `A${row}`, item.invoiceNo);
        setCellValue(workbook, "Import Goods", `B${row}`, item.invoiceValue);
        setCellValue(workbook, "Cr.Dr", `A${row}`, item.gstin);
        setCellValue(workbook, "Cr.Dr", `B${row}`, item.supplier);
        setCellValue(workbook, "Cr.Dr Unregistered", `A${row}`, item.supplier);
        setCellValue(workbook, "Cr.Dr Unregistered", `B${row}`, item.taxableValue);
        setCellValue(workbook, "Nil Rated", `A${row}`, "Inter-State");
        setCellValue(workbook, "Nil Rated", `B${row}`, item.taxableValue);
        setCellValue(workbook, "ISD", `A${row}`, item.gstin);
        setCellValue(workbook, "ISD", `B${row}`, item.invoiceNo);
        setCellValue(workbook, "TDS and TCS", `A${row}`, item.gstin);
        setCellValue(workbook, "TDS and TCS", `B${row}`, item.taxableValue);
        setCellValue(workbook, "Advance Paid", `A${row}`, item.invoiceDate);
        setCellValue(workbook, "Advance Paid", `B${row}`, item.taxableValue);
        setCellValue(workbook, "Advance Adjusted", `A${row}`, item.invoiceDate);
        setCellValue(workbook, "Advance Adjusted", `B${row}`, item.taxableValue);
        setCellValue(workbook, "ITC Reversal", `A${row}`, item.gstin);
        setCellValue(workbook, "ITC Reversal", `B${row}`, item.taxableValue);
        setCellValue(workbook, "HSN Summary", `A${row}`, "5208");
        setCellValue(workbook, "HSN Summary", `B${row}`, "Cotton Fabric");
        setCellValue(workbook, "HSN Summary", `C${row}`, item.taxableValue);
        setCellValue(workbook, "Master", `A${row}`, "System Generated");
        setCellValue(workbook, "Dropdowns", `A${row}`, "Auto Filled");
      });

      const excelBuffer = XLSX.write(workbook, { type: "array", bookType: "xlsx", cellStyles: true });
      saveAs(new Blob([excelBuffer], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" }), "Govt_GSTR2_Report.xlsx");
    } catch (error) {
      console.error("Govt Excel Error:", error);
      alert(error.message || "Unable to generate govt excel.");
    }
  };

  const downloadJSON = () => {
    const jsonBlob = new Blob([JSON.stringify(purchaseData, null, 2)], { type: "application/json" });
    saveAs(jsonBlob, "GSTR2_Report.json");
  };

  const handleDownload = async () => {
    if (fileType === "software_excel") { downloadSoftwareExcel(); return; }
    if (fileType === "govt_excel") { await downloadGovtExcel(); return; }
    if (fileType === "json") { downloadJSON(); }
  };

  return (
    <div className={`main ${collapsed ? "collapsed" : ""}`}>
      <div className="gstr-container">
        <h2 className="gstr-title">GSTR-2 Report</h2>
        <div className="gstr-card">
          <div className="gstr-left">
            <div className="gstr-switch-row">
              <span className={mode === "month" ? "label active" : "label"}>Month</span>
              <div className={`gstr-switch ${mode === "quarter" ? "right" : ""}`} onClick={() => setMode((prev) => prev === "month" ? "quarter" : "month")}>
                <div className="gstr-switch-thumb"></div>
              </div>
              <span className={mode === "quarter" ? "label active" : "label"}>Quarterly</span>
            </div>
            {mode === "month" ? (
              <input type="month" className="gstr-input" value={month} onChange={(e) => setMonth(e.target.value)} />
            ) : (
              <select className="gstr-input" value={quarter} onChange={(e) => setQuarter(e.target.value)}>
                <option value="">Select Quarter</option>
                <option value="Q1">Q1 (Apr - Jun)</option>
                <option value="Q2">Q2 (Jul - Sep)</option>
                <option value="Q3">Q3 (Oct - Dec)</option>
                <option value="Q4">Q4 (Jan - Mar)</option>
              </select>
            )}
          </div>
          <div className="gstr-right">
            <label>Type of File</label>
            <select className="gstr-input" value={fileType} onChange={(e) => setFileType(e.target.value)}>
              <option value="software_excel">Software Excel</option>
              <option value="govt_excel">Govt Excel</option>
              <option value="json">JSON</option>
            </select>
          </div>
        </div>
        <div className="gstr-action">
          <button className="gstr-download-btn" onClick={handleDownload} disabled={loading || purchaseData.length === 0}>
            {loading ? "Loading..." : "⬇ Download"}
          </button>
        </div>
        {error && <p style={{ color: "red", marginTop: 10 }}>{error}</p>}
        {!loading && !error && purchaseData.length === 0 && (
          <p style={{ color: "#888", marginTop: 10 }}>No data available for the selected period.</p>
        )}
      </div>
    </div>
  );
};

export default GSTR2Report;
